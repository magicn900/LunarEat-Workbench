

test('多负责人共享一条任务，筛选、取消分配与刷新保持一致', async ({ page }) => {
    await login(page); await openSchedule(page);
    await page.getByRole('button', { name: '新建任务', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('任务标题', { exact: true }).fill('多人共同负责测试');
    await dialog.getByRole('checkbox', { name: 'designer', exact: true }).check();
    await dialog.getByRole('checkbox', { name: 'developer', exact: true }).check();
    await dialog.getByLabel('开始日期', { exact: true }).fill(localToday());
    await dialog.getByLabel('结束日期', { exact: true }).fill(localToday());
    await dialog.getByRole('button', { name: '保存任务', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const rows = page.locator('.schedule-task-open').filter({ hasText: '多人共同负责测试' });
    await expect(rows).toHaveCount(2);
    await page.getByRole('button', { name: '只看我的', exact: true }).click();
    await expect(rows).toHaveCount(1);
    await rows.click();
    await expect(dialog.getByRole('checkbox', { name: 'developer', exact: true })).toBeChecked();
    await dialog.getByRole('checkbox', { name: 'developer', exact: true }).uncheck();
    await dialog.getByRole('button', { name: '保存任务', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await page.reload(); await openSchedule(page);
    await expect(rows).toHaveCount(1);
    const snapshot = await (await page.request.get('/api/schedule', { headers })).json();
    const matches = snapshot.tasks.filter((task: any) => task.title === '多人共同负责测试');
    expect(matches).toHaveLength(1);
    expect(matches[0].ownerIds).toHaveLength(1);
});
