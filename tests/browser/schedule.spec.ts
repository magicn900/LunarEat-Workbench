test('并发冲突保留输入，不覆盖其他人的修改', async ({ page }) => {
    await login(page); const response = await page.request.post('/api/schedule/tasks', { headers, data: { requestId: crypto.randomUUID(), version: 0, task: { ...emptyTask, title: '排期测试 · 冲突保护' } } });
    expect(response.ok()).toBe(true); const original = await response.json(); await openSchedule(page);
    await page.locator('.schedule-backlog-list button').filter({ hasText: original.title }).click();
    await page.getByRole('dialog').getByLabel('任务标题', { exact: true }).fill('我的未保存输入');
    const { id, version, created, updated, ...fields } = original;
    expect((await page.request.post('/api/schedule/tasks', { headers, data: { requestId: crypto.randomUUID(), id, version, task: { ...fields, title: '其他人的修改' } } })).ok()).toBe(true);
    await page.getByRole('button', { name: '保存任务', exact: true }).click();
    await expect(page.getByRole('dialog').getByRole('alert')).toContainText('任务已被他人修改');
    await expect(page.getByRole('dialog').getByLabel('任务标题', { exact: true })).toHaveValue('我的未保存输入');
    const snapshot = await (await page.request.get('/api/schedule', { headers })).json();
    expect(snapshot.tasks.find((task: any) => task.id === id).title).toBe('其他人的修改');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('dialog').getByRole('button', { name: '重新读取', exact: true }).click();
    await expect(page.getByRole('dialog').getByLabel('任务标题', { exact: true })).toHaveValue('其他人的修改');
    await page.getByRole('dialog').getByLabel('任务标题', { exact: true }).fill('我的未保存输入');
    await page.route('**/api/schedule', route => route.fulfill({ status: 403, contentType: 'application/json', body: JSON.stringify({ error: '缺少权限: schedule.read' }) }));
    await page.evaluate(() => window.dispatchEvent(new Event('focus')));
    await expect(page.locator('.schedule-page > .schedule-error')).toContainText('schedule.read');
    await expect(page.getByRole('dialog').getByLabel('任务标题', { exact: true })).toHaveValue('我的未保存输入');
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).first().click();
    await expect(page.getByRole('dialog')).not.toBeVisible();
});
test('仅排期权限账号可独立访问，只能更新自己的任务', async ({ page }) => {
    await login(page, 'test-admin');
    const username = 'schedule-member-' + Date.now();
    const created = await page.request.post('/api/admin/users', { headers, data: { username, password: 'e2e-password-123' } }); expect(created.ok()).toBe(true); const userId = (await created.json()).id;
    expect((await page.request.post('/api/admin/member', { headers, data: { userId, projectId: 'demo', scopes: ['schedule.read', 'schedule.update'], expectedScopes: null } })).ok()).toBe(true);
    await login(page);
    expect((await page.request.post('/api/schedule/tasks', { headers, data: { requestId: crypto.randomUUID(), version: 0, task: { ...emptyTask, title: '排期测试 · 本人更新', ownerIds: [userId] } } })).ok()).toBe(true);
    await login(page, username);
    await expect(page.getByRole('heading', { name: '你已加入项目' })).toBeVisible();
    await page.getByRole('button', { name: '打开任务排期', exact: true }).click();
    await expect(page.getByRole('heading', { name: '任务排期', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: '新建任务', exact: true })).toHaveCount(0);
    await expect(page.locator('.schedule-resize')).toHaveCount(0);
    await page.locator('.schedule-backlog-list button').filter({ hasText: '排期测试 · 本人更新' }).click();
    const dialog = page.getByRole('dialog');
    for (const checkbox of await dialog.getByRole('group', { name: '负责人', exact: true }).getByRole('checkbox').all()) await expect(checkbox).toBeDisabled();
    await expect(dialog.getByRole('combobox', { name: '父任务', exact: true })).toBeDisabled();
    await expect(dialog.getByLabel('任务标题', { exact: true })).toBeDisabled();
    await dialog.getByRole('combobox', { name: '状态', exact: true }).selectOption('doing');
    await dialog.getByRole('button', { name: '保存任务', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await expect(page.locator('.schedule-backlog-list button').filter({ hasText: '排期测试 · 本人更新' })).toContainText('进行中');
});
